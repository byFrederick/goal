package main

import (
	"bytes"
	"fmt"
	"maps"
	"slices"
	"strings"
)

// renderTS writes auth/'s roles, auth/src/access.gen.ts: the organization and factory roles, and
// Better Auth's access control (spec 3 §8.6): its statements are every better_auth action of
// the table, and each organization role holds the actions of the permissions it holds.
func renderTS(t table) ([]byte, error) {
	var b bytes.Buffer

	b.WriteString("// Code generated by cmd/permgen from contracts/api/permissions.yaml. DO NOT EDIT.\n\n")
	b.WriteString("import { createAccessControl } from 'better-auth/plugins/access';\n\n")
	b.WriteString("/** The organization roles of contracts/api/permissions.yaml. */\n")
	fmt.Fprintf(&b, "export const orgRoles = %s as const;\n", tsList(t.OrgRoles))
	b.WriteString("export type OrgRole = (typeof orgRoles)[number];\n\n")
	b.WriteString("/** The factory roles, a ladder, lowest first: each includes the one before. */\n")
	fmt.Fprintf(&b, "export const factoryRoles = %s as const;\n", tsList(t.FactoryRoles))
	b.WriteString("export type FactoryRole = (typeof factoryRoles)[number];\n\n")
	b.WriteString("/** Better Auth's access-control statements: every better_auth action of the table. */\n")
	b.WriteString("export const statements = {\n")

	for _, line := range tsStatements(betterAuthOf(t.Permissions)) {
		fmt.Fprintf(&b, "  %s,\n", line)
	}

	b.WriteString("} as const;\n\n")
	b.WriteString("export const ac = createAccessControl(statements);\n\n")
	b.WriteString("/** Each organization role, holding the better_auth actions of the permissions it holds. */\n")
	b.WriteString("export const roles = {\n")

	for _, role := range t.OrgRoles {
		var held []permission

		for _, p := range t.Permissions {
			if slices.Contains(p.OrgRoles, role) {
				held = append(held, p)
			}
		}

		statements := "{}"
		if lines := tsStatements(betterAuthOf(held)); len(lines) > 0 {
			statements = "{ " + strings.Join(lines, ", ") + " }"
		}

		fmt.Fprintf(&b, "  %s: ac.newRole(%s),\n", role, statements)
	}

	b.WriteString("} satisfies Record<OrgRole, unknown>;\n")

	return b.Bytes(), nil
}

// betterAuthOf is the union of the better_auth actions of permissions, by resource.
func betterAuthOf(permissions []permission) map[string][]string {
	union := map[string][]string{}

	for _, p := range permissions {
		for resource, actions := range p.BetterAuth {
			for _, a := range actions {
				if !slices.Contains(union[resource], a) {
					union[resource] = append(union[resource], a)
				}
			}
		}
	}

	return union
}

// tsStatements renders each resource as `resource: ['action', …]`, resources and actions sorted.
func tsStatements(byResource map[string][]string) []string {
	lines := make([]string, 0, len(byResource))

	for _, resource := range slices.Sorted(maps.Keys(byResource)) {
		lines = append(lines, resource+": "+tsList(slices.Sorted(slices.Values(byResource[resource]))))
	}

	return lines
}

// tsList renders names, which load has checked are plain identifiers, as a single-quoted array.
func tsList(names []string) string {
	quoted := make([]string, len(names))
	for i, n := range names {
		quoted[i] = "'" + n + "'"
	}

	return "[" + strings.Join(quoted, ", ") + "]"
}
