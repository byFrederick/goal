package main

import (
	"bytes"
	"fmt"
	"go/format"
	"maps"
	"slices"
	"strconv"
	"strings"
)

// renderGo writes goald's table, internal/api/permissions_gen.go: permissionRules (each
// permission by name, as the hand-written rule type of internal/api) and operationScopes (each
// operationId's permission), both sorted by key.
func renderGo(t table) ([]byte, error) {
	var b bytes.Buffer

	b.WriteString("// Code generated by cmd/permgen from api/permissions.yaml and api/openapi.yaml. DO NOT EDIT.\n\n")
	b.WriteString("package api\n\n")
	b.WriteString("// permissionRules is every permission of api/permissions.yaml, by name.\n")
	b.WriteString("var permissionRules = map[string]rule{\n")

	for _, p := range t.Permissions {
		fields := []string{"level: " + strconv.Quote(p.Level)}

		if len(p.OrgRoles) > 0 {
			roles := make([]string, len(p.OrgRoles))
			for i, r := range p.OrgRoles {
				roles[i] = strconv.Quote(r)
			}

			fields = append(fields, "orgRoles: []string{"+strings.Join(roles, ", ")+"}")
		}

		if p.FactoryRole != "" {
			fields = append(fields, "factoryRole: "+strconv.Quote(p.FactoryRole))
		}

		for _, f := range []struct {
			name string
			on   bool
		}{{"keys", p.Keys}, {"pat", p.PAT}, {"fresh", p.Fresh}, {"platformAdmin", p.PlatformAdmin}} {
			if f.on {
				fields = append(fields, f.name+": true")
			}
		}

		fmt.Fprintf(&b, "\t%s: {%s},\n", strconv.Quote(p.Name), strings.Join(fields, ", "))
	}

	b.WriteString("}\n\n")
	b.WriteString("// operationScopes is the x-goal-scope of every operation of api/openapi.yaml, by operationId.\n")
	b.WriteString("var operationScopes = map[string]string{\n")

	for _, id := range slices.Sorted(maps.Keys(t.Scopes)) {
		fmt.Fprintf(&b, "\t%s: %s,\n", strconv.Quote(id), strconv.Quote(t.Scopes[id]))
	}

	b.WriteString("}\n")

	return format.Source(b.Bytes())
}
