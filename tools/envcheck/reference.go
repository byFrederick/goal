package main

import (
	"slices"
	"strings"
)

// readerTitles are the reference's sections, in order.
var readerTitles = []struct{ reader, title string }{
	{readerGoald, "goald (`cmd/goald`)"},
	{readerEgress, "goal-egress (`cmd/goal-egress`)"},
	{readerCLI, "The goal CLI (`cmd/goal`)"},
	{readerAuth, "The auth service (`apps/auth`)"},
	{readerWorker, "The agent worker (`apps/worker`)"},
	{readerControlWorker, "The control Worker (`apps/control-worker`, its vars and Secrets Store bindings in `deploy/cloudflare/wrangler.jsonc`)"},
	{readerCompose, "Docker Compose (`compose.yaml`)"},
	{readerTaskfile, "The Taskfiles (`Taskfile.yml` and the area Taskfiles it includes)"},
}

// reference renders docs/reference/environment.md: one table per reader.
func reference(reg registry) string {
	var b strings.Builder

	b.WriteString("<!-- Generated by tools/envcheck from contracts/env.yaml. Do not edit: change the registry and run task env:check -- -write. -->\n\n")
	b.WriteString("# Environment variables\n\n")
	b.WriteString("Every environment variable a Goal process reads, by the process that reads it. ")
	b.WriteString("The registry, [contracts/env.yaml](../../contracts/env.yaml), holds names, meanings, the default the code falls back to ")
	b.WriteString("and when a variable is required, never a secret or an example; ")
	b.WriteString("`task env:check` fails when the code reads a variable it does not declare, or when it declares one nothing reads.\n\n")
	b.WriteString("Classes: **public** may be shown to anyone who uses the platform; **config** is a setting of the install, not a secret; ")
	b.WriteString("**secret** is a credential, which never reaches a log, a commit or a prompt. ")
	b.WriteString("Required means the process refuses to start without it, or names the reader or condition that needs it; ")
	b.WriteString("every other variable falls back to its default or turns a feature off. An empty Default means the code has none, or the registry does not state it yet.\n")

	for _, rt := range readerTitles {
		var rows []entry

		for _, e := range reg.Variables {
			if slices.Contains(e.Readers, rt.reader) {
				rows = append(rows, e)
			}
		}

		if len(rows) == 0 {
			continue
		}

		b.WriteString("\n## " + rt.title + "\n\n")
		b.WriteString("| Name | Class | Required | Default | Meaning |\n| --- | --- | --- | --- | --- |\n")

		for _, e := range rows {
			req := "no"

			switch {
			case e.Required:
				req = "yes"
			case e.RequiredWhen != "":
				req = cell(e.RequiredWhen)
			}

			def := ""
			if e.Default != "" {
				// A code span shows < and > as they are; only the pipe needs escaping in a table.
				def = "`" + strings.ReplaceAll(e.Default, "|", `\|`) + "`"
			}

			b.WriteString("| `" + e.Name + "` | " + e.Class + " | " + req + " | " + def + " | " + cell(e.Meaning) + " |\n")
		}
	}

	return b.String()
}

// cellEscaper escapes text for a table cell: the pipe would end the cell, and < and > would
// parse as HTML and vanish from the page.
var cellEscaper = strings.NewReplacer("|", `\|`, "<", "&lt;", ">", "&gt;")

// cell escapes a meaning or a required condition for a table cell.
func cell(s string) string { return cellEscaper.Replace(s) }
