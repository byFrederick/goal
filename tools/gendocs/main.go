// Command gendocs writes the docs generated from a source, in two groups.
//
// The indexes of one file per entry, so two pull requests that each add an entry do not conflict
// on a shared file (ADR 0015, decision 6):
//
//   - docs/engineering/change-map.md, from the page docs/engineering/change-map/_page.md and one
//     entry file per row beside it (docs/engineering/change-map/NN-<slug>.md), rows in file-name order;
//   - docs/adr/README.md, one line per ADR (docs/adr/NNNN-<slug>.md): its number, the title of its
//     "# ADR NNNN — <title>" heading and the first " · " part of its "Status:" line.
//
// A branch adds or edits only their entry files and never edits or regenerates the two indexes:
// the docs-gen workflow (.github/workflows/docs-gen.yml) runs gendocs on main after a merge and
// commits them.
//
// The reference pages of the docs site (apps/docs/src/content/docs/reference/, reference.go): the
// CLI from internal/cli's usage text, the factory definition from
// contracts/definitions/factory.schema.json, and the environment variables and the glossary from
// docs/reference/. A branch that changes a source regenerates them with gendocs -reference (task
// docs:ref:gen), which writes nothing else.
//
// gendocs -check writes nothing. It fails on a malformed entry or ADR but not when the two indexes
// are stale or missing, and it fails when a reference page differs from what its source
// generates. `task docs:gen`, `task docs:ref:gen` and `task docs:check` run it.
package main

import (
	"flag"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path"
	"strings"

	"github.com/byFrederick/goal/internal/cli"
)

const (
	changeMapFile = "docs/engineering/change-map.md"
	changeMapDir  = "docs/engineering/change-map"
	adrIndexFile  = "docs/adr/README.md"
	adrDir        = "docs/adr"
)

// generatedNote heads every file gendocs writes.
const generatedNote = "<!-- Generated by tools/gendocs. Do not edit: change the entry files in docs/engineering/change-map/ or the ADRs in docs/adr/ and run task docs:gen. -->\n"

func main() {
	if err := run(os.Args[1:], os.Stdout, cli.Usage()); err != nil {
		fmt.Fprintln(os.Stderr, "gendocs:", err)
		os.Exit(1)
	}
}

// run runs gendocs with the CLI's usage text usage, the source of the CLI reference page.
func run(args []string, stdout io.Writer, usage string) error {
	flags := flag.NewFlagSet("gendocs", flag.ContinueOnError)
	flags.SetOutput(io.Discard)

	dir := flags.String("C", ".", "the repository")
	check := flags.Bool("check", false, "write nothing; fail when an entry file or ADR does not render or a reference page is stale")
	referenceOnly := flags.Bool("reference", false, "write only the reference pages of the docs site")

	if err := flags.Parse(args); err != nil {
		return err
	}

	if flags.NArg() > 0 {
		return fmt.Errorf("unexpected argument %q", flags.Arg(0))
	}

	root, err := os.OpenRoot(*dir)
	if err != nil {
		return fmt.Errorf("open the repository: %w", err)
	}
	defer func() { _ = root.Close() }() // every write is checked where it happens

	pages, err := renderReference(root.FS(), usage)
	if err != nil {
		return err
	}

	if *referenceOnly && !*check {
		return write(root, referencePages, pages)
	}

	files, err := render(root.FS())
	if err != nil {
		return err
	}

	if *check {
		if err := checkReference(root.FS(), pages); err != nil {
			return err
		}

		_, _ = fmt.Fprintf(stdout, "%d generated files render from their sources and %d reference pages are current\n", len(files), len(pages))

		return nil
	}

	if err := write(root, generatedFiles, files); err != nil {
		return err
	}

	return write(root, referencePages, pages)
}

// write writes the files names of files into root, making their directories.
func write(root *os.Root, names []string, files map[string]string) error {
	for _, name := range names {
		if err := root.MkdirAll(path.Dir(name), 0o755); err != nil {
			return fmt.Errorf("make the directory of %s: %w", name, err)
		}

		if err := root.WriteFile(name, []byte(files[name]), 0o644); err != nil {
			return fmt.Errorf("write %s: %w", name, err)
		}
	}

	return nil
}

// checkReference fails, naming each one, when a reference page differs from pages, what its
// source generates.
func checkReference(fsys fs.FS, pages map[string]string) error {
	var stale []string

	for _, name := range referencePages {
		got, err := fs.ReadFile(fsys, name)
		if err != nil || string(got) != pages[name] {
			stale = append(stale, name)
		}
	}

	if len(stale) > 0 {
		return fmt.Errorf("%w: %s; run task docs:ref:gen", errStaleReference, strings.Join(stale, ", "))
	}

	return nil
}

// generatedFiles are the two indexes gendocs writes, in report order; -check is lenient about them.
var generatedFiles = []string{changeMapFile, adrIndexFile}

// render renders every generated file from the repository fsys, by its slash-separated path.
func render(fsys fs.FS) (map[string]string, error) {
	changeMap, err := renderChangeMap(fsys)
	if err != nil {
		return nil, err
	}

	adrIndex, err := renderADRIndex(fsys)
	if err != nil {
		return nil, err
	}

	return map[string]string{changeMapFile: changeMap, adrIndexFile: adrIndex}, nil
}
