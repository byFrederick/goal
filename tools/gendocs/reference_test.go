func TestReference_RendersEachPageFromItsSource(t *testing.T) {
	t.Parallel()

	pages, err := renderReference(os.DirFS("testdata/repo"), testUsage)
	if err != nil {
		t.Fatal(err)
	}

	for file, want := range map[string]string{
		cliPage: wantCLIPage, definitionPage: wantDefinitionPage, environmentPage: wantEnvironmentPage, glossaryPage: wantGlossaryPage,
	} {
		if got := pages[file]; got != want {
			t.Errorf("%s =\n%s\nwant\n%s", file, got, want)
		}
	}
}

// staleCheck makes page stale in a copy of the fixture repository and shows that -check fails
// naming it and the task to run, and passes once the reference is regenerated.
func staleCheck(t *testing.T, page string) {
	t.Helper()

	dir := copyRepo(t, "repo")

	if err := openRoot(t, dir).WriteFile(page, []byte("---\ntitle: Stale\n---\n\nedited by hand\n"), 0o600); err != nil {
		t.Fatal(err)
	}

	err := run([]string{"-C", dir, checkFlag}, &bytes.Buffer{}, testUsage)
	if err == nil || !strings.Contains(err.Error(), page) || !strings.Contains(err.Error(), "task docs:ref:gen") {
		t.Fatalf("check with a stale %s = %v, want an error naming it and task docs:ref:gen", page, err)
	}

	if err := run([]string{"-C", dir, "-reference"}, &bytes.Buffer{}, testUsage); err != nil {
		t.Fatal(err)
	}

	if err := run([]string{"-C", dir, checkFlag}, &bytes.Buffer{}, testUsage); err != nil {
		t.Errorf("check after regenerating: %v, want it to pass", err)
	}
}

