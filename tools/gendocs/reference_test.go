// The real usage text: every "goal ..." line becomes a form of a section, so the page drops no
// command.
func TestReference_EveryCommandOfTheUsageHasASection(t *testing.T) {
	t.Parallel()

	commands, _, err := parseUsage(cli.Usage())
	if err != nil {
		t.Fatal(err)
	}

	var forms []string
	for _, c := range commands {
		forms = append(forms, c.forms...)
	}

	lines := regexp.MustCompile(`(?m)^  goal .*$`).FindAllString(cli.Usage(), -1)
	if len(forms) != len(lines) {
		t.Fatalf("%d forms parsed from %d command lines", len(forms), len(lines))
	}

	// A command's forms are grouped under its first, so match each line to any form left.
	for _, line := range lines {
		line = strings.TrimSpace(line)

		i := slices.IndexFunc(forms, func(f string) bool { return line == f || strings.HasPrefix(line, f+" ") })
		if i < 0 {
			t.Errorf("no form parsed from %q", line)

			continue
		}

		if strings.Count(forms[i], "[") != strings.Count(forms[i], "]") {
			t.Errorf("form %q has unbalanced brackets: its description was cut into it", forms[i])
		}

		forms = slices.Delete(forms, i, i+1)
	}

	page := renderCLIPage(commands, nil)
	for _, c := range commands {
		if !strings.Contains(page, "\n## "+c.name+"\n") {
			t.Errorf("the page has no section for %s", c.name)
		}

		if c.description() == "" {
			t.Errorf("%s has no description", c.name)
		}
	}
}
